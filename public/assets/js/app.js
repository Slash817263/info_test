// Toggle password visibility
const togglePwdBtn = document.getElementById('toggle-student-password');
if (togglePwdBtn) {
    togglePwdBtn.addEventListener('click', (e) => {
        e.preventDefault();
        const pwdInput = document.getElementById('student-password');
        if (!pwdInput) return;
        const eyeShow = togglePwdBtn.querySelector('.eye-show');
        const eyeHide = togglePwdBtn.querySelector('.eye-hide');
        if (pwdInput.type === 'password') {
            pwdInput.type = 'text';
            if (eyeShow) eyeShow.style.display = 'none';
            if (eyeHide) eyeHide.style.display = 'inline-block';
            togglePwdBtn.setAttribute('aria-label', 'Ascunde parola');
        } else {
            pwdInput.type = 'password';
            if (eyeShow) eyeShow.style.display = 'inline-block';
            if (eyeHide) eyeHide.style.display = 'none';
            togglePwdBtn.setAttribute('aria-label', 'Afișează parola');
        }
    });
}

